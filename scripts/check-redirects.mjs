#!/usr/bin/env node
// check-redirects.mjs — the dev→help URL contract, as a checkable artifact.
//
// WHY
//   developers.keboola.com retirement (PRDCT-565) needs one consolidated
//   "every dev URL → final help URL" table; today that truth is split across
//   PLACEMENT-MAP.md, MIGRATION-REPORT(.md/-phase2.md) and batch PRs, and the
//   in-build redirects are meta-refresh pages, not 301 rules. This script makes
//   the table a build artifact and checks it three ways.
//
// USAGE
//   node scripts/check-redirects.mjs --gen        # (re)generate the TSV from PLACEMENT-MAP.md — note that
//                                                 # PLACEMENT-MAP.md is a local migration working file and is
//                                                 # NOT in this repo, so the committed TSV is the source of
//                                                 # truth here; edit it directly when a page finds its home
//   node scripts/check-redirects.mjs --build      # CI gate against dist/ (run `npm run build` first):
//                                                 #   FAILs when a dev path that used to resolve now resolves
//                                                 #   nowhere. Dev paths never yet migrated are tolerated —
//                                                 #   they are listed in _data/redirects/not-yet-migrated.txt
//   node scripts/check-redirects.mjs --build --baseline   # rewrite that not-yet-migrated list from this build
//   node scripts/check-redirects.mjs --flippable  # absolute developers.keboola.com links in content whose target already lives on help
//   node scripts/check-redirects.mjs --live       # cutover day: HTTP developers.keboola.com/<path> must 301 to the mapped help URL
//
// TSV columns: dev_path <TAB> final_help_path <TAB> status
//   moved    — page gets a topic home on help (final_help_path)
//   redirect — dev landing/duplicate; 301 straight to the canonical
//   dies     — site chrome (404, homepage) — no mapping required, listed for completeness
//   unsure   — PLACEMENT-MAP row awaiting a PRDCT-550 call; final path is the proposal

import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const MAP_MD = path.join(ROOT, 'PLACEMENT-MAP.md');
const TSV = path.join(ROOT, '_data', 'redirects', 'dev-to-help.tsv');
const DIST = path.join(ROOT, 'dist');
const DEV_HOST = 'https://developers.keboola.com';
const HELP_HOST = 'https://help.keboola.com';

const mode = process.argv[2];
const clean = (p) => {
  if (!p || p === '—' || p === '-') return null;
  let s = p.replace(/`/g, '').trim();
  if (!s.startsWith('/')) return null;
  if (!s.endsWith('/') && !/\.[a-z]+$/.test(s)) s += '/';
  return s;
};

function parsePlacementMap() {
  const rows = [];
  for (const line of fs.readFileSync(MAP_MD, 'utf8').split('\n')) {
    const m = line.match(/^\| `([^`]+\.md)` \| `([^`]+)` \| ([^|]+) \| ([^|]*) \|([^|]*)\|([^|]*)\|(.*)\|?\s*$/);
    if (!m) continue;
    const [, , oldUrl, section, target, , conf, dedup] = m;
    const dev = clean(oldUrl); // clean() keeps .html forms as-is
    if (!dev) continue;
    const tgt = clean(target);
    let status;
    if (/NOT MIGRATED/i.test(dedup) && !tgt) status = 'dies';
    else if (/REDIRECT/i.test(dedup) || section.trim().startsWith('—')) status = 'redirect';
    else status = 'moved';
    if (/UNSURE/i.test(dedup) || /UNSURE/i.test(section)) status = 'unsure';
    rows.push({ dev, tgt: tgt ?? '', status, conf: conf.trim() });
  }
  return rows;
}

function gen() {
  const rows = parsePlacementMap();
  // PLACEMENT-MAP asserts 175/175 coverage — any parse below that is silent row loss
  if (rows.length < 175) fail(`parsed only ${rows.length}/175 rows from PLACEMENT-MAP.md — format drifted, refusing to write a lossy map`);
  fs.mkdirSync(path.dirname(TSV), { recursive: true });
  const body = rows.map((r) => `${r.dev}\t${r.tgt}\t${r.status}`).join('\n');
  fs.writeFileSync(TSV, `# generated by scripts/check-redirects.mjs --gen from PLACEMENT-MAP.md — do not hand-edit\n# dev_path\tfinal_help_path\tstatus\n${body}\n`);
  const c = count(rows.map((r) => r.status));
  console.log(`✓ ${TSV.replace(ROOT + '/', '')}: ${rows.length} rows (${fmt(c)})`);
}

function readTsv() {
  if (!fs.existsSync(TSV)) fail('map missing — run --gen first');
  return fs.readFileSync(TSV, 'utf8').split('\n')
    .filter((l) => l && !l.startsWith('#'))
    .map((l) => { const [dev, tgt, status] = l.split('\t'); return { dev, tgt, status }; });
}

// A path "resolves" in dist if a page (real or redirect stub) exists there.
// Each candidate must be a FILE — a page directory outlives its index.html
// (co-located images keep it alive), so an existsSync() on the bare directory
// would report a route as served after its page stopped being built.
const isFile = (f) => { try { return fs.statSync(f).isFile(); } catch { return false; } };
const inDist = (p) => {
  if (!p) return false;
  const c = p.replace(/^\//, '').replace(/\/$/, '');
  return ['index.html', '.html'].some((suf) =>
    isFile(path.join(DIST, suf === 'index.html' ? path.join(c, 'index.html') : c + suf))) ||
    isFile(path.join(DIST, c)); // literal (e.g. 404.html)
};

// Dev URLs with no home in dist yet — the migration's remaining work, kept as a
// committed list. The gate is a ratchet against it: a dev URL that used to land
// somewhere and now lands nowhere is a regression this branch caused; one that
// never landed is inherited debt. The file shrinks as batches merge, so it also
// reads as the live "what's left to migrate" list.
const NOT_MIGRATED = path.join(ROOT, '_data', 'redirects', 'not-yet-migrated.txt');

function lostSet() {
  if (!fs.existsSync(DIST)) fail('dist/ missing — run `npm run build` first');
  const rows = readTsv();
  const lost = [], pending = [];
  for (const r of rows) {
    if (r.status === 'dies') continue;
    const devServes = inDist(r.dev);
    const finalServes = inDist(r.tgt);
    if (!devServes && !finalServes) lost.push(r.dev);
    else if (r.tgt && !finalServes) pending.push(`${r.dev} → ${r.tgt} (final target not built yet)`);
  }
  return { rows, lost: lost.sort(), pending };
}

function writeBaseline() {
  const { lost } = lostSet();
  fs.mkdirSync(path.dirname(NOT_MIGRATED), { recursive: true });
  fs.writeFileSync(NOT_MIGRATED,
    `# Dev URLs that resolve nowhere in the current build — inherited migration debt (PRDCT-565).\n`
    + `# Regenerate: npm run check:redirects:baseline. Shrinking is progress; growing means a\n`
    + `# branch orphaned a dev URL that used to land somewhere.\n`
    + `${lost.join('\n')}\n`);
  console.log(`✓ baseline written: ${NOT_MIGRATED.replace(ROOT + '/', '')} — ${lost.length} dev URL(s) still unmigrated`);
}

function checkBuild() {
  // Soft skip #1 — the map itself is not here yet. It arrives with PRDCT-572 and
  // this gate ships ahead of it, so a missing map is "nothing to check", not a
  // failure. Merge order is not ours to control.
  if (!fs.existsSync(TSV)) {
    console.log(`· skipped: no ${TSV.replace(ROOT + '/', '')} in this tree yet (arrives with PRDCT-572).`);
    return;
  }

  const { rows, lost, pending } = lostSet();
  const known = fs.existsSync(NOT_MIGRATED)
    ? new Set(fs.readFileSync(NOT_MIGRATED, 'utf8').split('\n').filter((l) => l && !l.startsWith('#')))
    : null;

  if (pending.length) {
    console.log(`… ${pending.length} pending (final home not merged yet — expected until batches land):`);
    pending.slice(0, 15).forEach((p) => console.log(`   ${p}`));
  }

  // Soft skip #2 — map present, baseline not. Never fail without a baseline: the
  // map arrives carrying ~119 dev URLs that have never been migrated, and failing
  // on inherited debt would redden main the moment PRDCT-572 lands. Report and pass;
  // `npm run check:redirects:baseline` turns the gate on.
  if (!known) {
    console.log(`· ${lost.length} of ${rows.length} mapped dev URL(s) resolve nowhere yet — no baseline committed, so this is a report, not a gate.`);
    lost.slice(0, 15).forEach((p) => console.log(`   ${p}`));
    if (lost.length > 15) console.log(`   …and ${lost.length - 15} more`);
    console.log(`  Run \`npm run check:redirects:baseline\` and commit ${NOT_MIGRATED.replace(ROOT + '/', '')} to start gating.`);
    return;
  }

  const regressed = lost.filter((p) => !known.has(p));
  const recovered = [...known].filter((p) => !lost.includes(p)).sort();

  if (recovered.length) {
    console.log(`✓ ${recovered.length} dev URL(s) now land somewhere — run \`npm run check:redirects:baseline\` to bank it.`);
    recovered.slice(0, 15).forEach((p) => console.log(`   ${p}`));
  }
  if (regressed.length) {
    console.error(`\n✗ dev→help contract: ${regressed.length} dev URL(s) this branch orphaned — they resolved before and resolve nowhere now:`);
    regressed.forEach((p) => console.error(`   ${p}`));
    console.error(`\nA page was moved, renamed or deleted without a redirect. Restore the route,\nadd a redirect, or update _data/redirects/dev-to-help.tsv to its new home.`);
    process.exit(1);
  }
  console.log(`✓ dev→help contract: no dev URL orphaned (${lost.length} still awaiting migration, ${rows.length} mapped).`);
}

function flippable() {
  const rows = readTsv();
  const byDev = new Map(rows.map((r) => [r.dev, r]));
  const hits = [];
  walk(path.join(ROOT, 'src', 'content', 'docs'), (f) => {
    if (!/\.(md|mdx)$/.test(f)) return;
    const text = fs.readFileSync(f, 'utf8');
    for (const m of text.matchAll(/https?:\/\/developers\.keboola\.com(\/[^\s)"'<>\]]*)/g)) {
      const p = clean(m[1].split('#')[0]);
      if (!p || p === '/') continue; // bare-domain links are a homepage-cutover call, not a mechanical flip
      const row = byDev.get(p);
      const target = row?.status === 'moved' || row?.status === 'redirect' ? row.tgt || p : null;
      if (target && inDist(target))
        hits.push(`${f.replace(ROOT + '/', '')}: ${m[0]} → ${target}`);
    }
  });
  if (!hits.length) return console.log('✓ no flippable dev-domain links (all remaining targets not migrated yet)');
  console.log(`${hits.length} link(s) can flip to internal now:`);
  hits.forEach((h) => console.log(`  ${h}`));
}

async function live() {
  const rows = readTsv().filter((r) => r.status !== 'dies');
  let bad = 0;
  for (const r of rows) {
    const res = await fetch(DEV_HOST + r.dev, { redirect: 'manual' }).catch(() => null);
    const loc = res?.headers.get('location') ?? '';
    const expected = HELP_HOST + (r.tgt || r.dev);
    const ok = res && [301, 308].includes(res.status) && (loc === expected || loc.replace(/\/$/, '') === expected.replace(/\/$/, ''));
    if (!ok) { bad++; console.error(`✗ ${r.dev}: got ${res?.status ?? 'ERR'} ${loc || ''} — want 301 ${expected}`); }
  }
  console.log(bad ? `✗ ${bad}/${rows.length} mismatches` : `✓ all ${rows.length} URLs 301 correctly`);
  if (bad) process.exit(1);
}

function walk(dir, fn) { for (const e of fs.readdirSync(dir, { withFileTypes: true })) { const p = path.join(dir, e.name); e.isDirectory() ? walk(p, fn) : fn(p); } }
function count(a) { return a.reduce((m, x) => (m[x] = (m[x] ?? 0) + 1, m), {}); }
function fmt(o) { return Object.entries(o).map(([k, v]) => `${v} ${k}`).join(', '); }
function fail(msg) { console.error(`✗ ${msg}`); process.exit(1); }

if (mode === '--gen') gen();
else if (mode === '--build') (process.argv[3] === '--baseline' ? writeBaseline() : checkBuild());
else if (mode === '--flippable') flippable();
else if (mode === '--live') await live();
else fail('usage: check-redirects.mjs --gen | --build [--baseline] | --flippable | --live');
