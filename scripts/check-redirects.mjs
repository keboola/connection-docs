#!/usr/bin/env node
// check-redirects.mjs — the dev→help URL contract, as a checkable artifact.
//
// WHY
//   developers.keboola.com retirement (PRDCT-565) needs one consolidated
//   "every dev URL → final help URL" table; today that truth is split across
//   PLACEMENT-MAP.md, MIGRATION-REPORT(.md/-phase2.md) and batch PRs, and the
//   in-build redirects are meta-refresh pages, not 301 rules. This script makes
//   the table a build artifact and checks it three ways.
//
// USAGE
//   node scripts/check-redirects.mjs --gen        # (re)generate _data/redirects/dev-to-help.tsv from PLACEMENT-MAP.md
//   node scripts/check-redirects.mjs --build      # verify against dist/ (run `npm run build` first):
//                                                 #   every dev path must resolve (real page or redirect page) — else FAIL
//   node scripts/check-redirects.mjs --flippable  # absolute developers.keboola.com links in content whose target already lives on help
//   node scripts/check-redirects.mjs --live       # cutover day: developers.keboola.com/<path> must 301 off the domain and land on the mapped URL
//   node scripts/check-redirects.mjs --vercel     # print vercel.json `redirects` so help's second hop is a real 301, not a meta-refresh
//
// TSV columns: dev_path <TAB> final_help_path <TAB> status
//   moved    — page gets a topic home on help (final_help_path)
//   redirect — dev landing/duplicate; 301 straight to the canonical
//   dies     — site chrome (404.html) — nothing to map, listed for completeness
//   external — deliberately not on help; 301 goes off-site (e.g. the tool's own repository)
//   unsure   — PLACEMENT-MAP row awaiting a PRDCT-550 call; final path is the proposal
//   alias    — not a page: a Jekyll redirect_from the dev site honours; help resolves it via redirect_from on the canonical page

import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const MAP_MD = path.join(ROOT, 'PLACEMENT-MAP.md');
const TSV = path.join(ROOT, '_data', 'redirects', 'dev-to-help.tsv');
const DIST = path.join(ROOT, 'dist');
const DEV_HOST = 'https://developers.keboola.com';
const HELP_HOST = 'https://help.keboola.com';

const mode = process.argv[2];
const clean = (p) => {
  if (!p || p === '—' || p === '-') return null;
  let s = p.replace(/`/g, '').trim();
  if (/^https?:\/\//.test(s)) return s;   // off-site destination — kept verbatim
  if (!s.startsWith('/')) return null;
  if (!s.endsWith('/') && !/\.[a-z]+$/.test(s)) s += '/';
  return s;
};

function parsePlacementMap() {
  const rows = [];
  for (const line of fs.readFileSync(MAP_MD, 'utf8').split('\n')) {
    const m = line.match(/^\| `([^`]+\.md)` \| `([^`]+)` \| ([^|]+) \| ([^|]*) \|([^|]*)\|([^|]*)\|(.*)\|?\s*$/);
    if (!m) continue;
    const [, , oldUrl, section, target, , conf, dedup] = m;
    const dev = clean(oldUrl); // clean() keeps .html forms as-is
    if (!dev) continue;
    const tgt = clean(target);
    let status;
    if (tgt && /^https?:\/\//.test(tgt)) status = 'external';
    else if (/\bALIAS\b/.test(dedup)) status = 'alias';
    else if (/NOT MIGRATED/i.test(dedup) && !tgt) status = 'dies';
    else if (/REDIRECT/i.test(dedup) || section.trim().startsWith('—')) status = 'redirect';
    else status = 'moved';
    if (/UNSURE/i.test(dedup) || /UNSURE/i.test(section)) status = 'unsure';
    rows.push({ dev, tgt: tgt ?? '', status, conf: conf.trim() });
  }
  return rows;
}

function gen() {
  const rows = parsePlacementMap();
  // PLACEMENT-MAP asserts 175/175 pages + 26 aliases — any parse below 201 is silent row loss
  if (rows.length < 201) fail(`parsed only ${rows.length}/201 rows from PLACEMENT-MAP.md — format drifted, refusing to write a lossy map`);
  fs.mkdirSync(path.dirname(TSV), { recursive: true });
  const body = rows.map((r) => `${r.dev}\t${r.tgt}\t${r.status}`).join('\n');
  fs.writeFileSync(TSV, `# generated by scripts/check-redirects.mjs --gen from PLACEMENT-MAP.md — do not hand-edit\n# dev_path\tfinal_help_path\tstatus\n${body}\n`);
  const c = count(rows.map((r) => r.status));
  console.log(`✓ ${TSV.replace(ROOT + '/', '')}: ${rows.length} rows (${fmt(c)})`);
}

function readTsv() {
  if (!fs.existsSync(TSV)) fail('map missing — run --gen first');
  return fs.readFileSync(TSV, 'utf8').split('\n')
    .filter((l) => l && !l.startsWith('#'))
    .map((l) => { const [dev, tgt, status] = l.split('\t'); return { dev, tgt, status }; });
}

// a path "resolves" in dist if a page (real or redirect stub) exists there
const inDist = (p) => {
  if (!p) return false;
  const c = p.replace(/^\//, '').replace(/\/$/, '');
  return ['index.html', '.html'].some((suf) =>
    fs.existsSync(path.join(DIST, suf === 'index.html' ? path.join(c, 'index.html') : c + suf))) ||
    (() => { try { return fs.statSync(path.join(DIST, c)).isFile(); } catch { return false; } })(); // literal file (e.g. 404.html)
};

// the meta-refresh target of a redirect page in dist, as a site-relative path; null if the path is not a redirect page
const redirectTargetInDist = (p) => {
  const c = p.replace(/^\//, '').replace(/\/$/, '');
  const f = path.join(DIST, c, 'index.html');
  if (!fs.existsSync(f)) return null;
  const m = fs.readFileSync(f, 'utf8').match(/http-equiv="refresh"\s+content="\d+;\s*url=([^"]+)"/i);
  return m ? m[1].replace(/^https?:\/\/help\.keboola\.com/, '') : null;
};
const samePath = (a, b) => a.replace(/\/$/, '') === b.replace(/\/$/, '');

function checkBuild() {
  if (!fs.existsSync(DIST)) fail('dist/ missing — run `npm run build` first');
  const rows = readTsv();
  const lost = [];
  const external = rows.filter((r) => r.status === 'external').length;
  for (const r of rows) {
    if (r.status === 'dies' || r.status === 'external') continue;
    const identity = !r.tgt || r.tgt === r.dev;
    if (identity) {
      if (!inDist(r.dev)) lost.push(`${r.dev} (page missing)`);
      continue;
    }
    // moved / redirect / alias: the edge host-swap forwards the dev path verbatim, so help must serve a
    // redirect page there that points at the contract target, and the target itself must exist.
    if (!inDist(r.tgt)) { lost.push(`${r.dev} → ${r.tgt} (target not built)`); continue; }
    const stub = redirectTargetInDist(r.dev);
    if (!stub) lost.push(`${r.dev} (no redirect page in dist — a host-swapped request would 404)`);
    else if (!samePath(stub, r.tgt)) lost.push(`${r.dev} redirects to ${stub}, contract says ${r.tgt}`);
  }
  if (external) console.log(`… ${external} URL(s) redirect off-site by decision (not expected in dist)`);
  if (lost.length) {
    console.error(`✗ ${lost.length} contract row(s) not honoured by dist:`);
    lost.forEach((p) => console.error(`   ${p}`));
    process.exit(1);
  }
  console.log(`✓ conservation holds: ${rows.length} mapped URLs — identity pages present, every moved/redirect/alias path serves a redirect page to its contract target`);
}

function flippable() {
  const rows = readTsv();
  const byDev = new Map(rows.map((r) => [r.dev, r]));
  const hits = [];
  walk(path.join(ROOT, 'src', 'content', 'docs'), (f) => {
    if (!/\.(md|mdx)$/.test(f)) return;
    const text = fs.readFileSync(f, 'utf8');
    for (const m of text.matchAll(/https?:\/\/developers\.keboola\.com(\/[^\s)"'<>\]]*)/g)) {
      const p = clean(m[1].split('#')[0]);
      if (!p || p === '/') continue; // bare-domain links are a homepage-cutover call, not a mechanical flip
      const row = byDev.get(p);
      const target = row?.status === 'moved' || row?.status === 'redirect' || row?.status === 'alias' ? row.tgt || p : null;
      if (target && inDist(target))
        hits.push(`${f.replace(ROOT + '/', '')}: ${m[0]} → ${target}`);
    }
  });
  if (!hits.length) return console.log('✓ no flippable dev-domain links (all remaining targets not migrated yet)');
  console.log(`${hits.length} link(s) can flip to internal now:`);
  hits.forEach((h) => console.log(`  ${h}`));
}

// The edge rule is a host-swap, so the first Location is help + the same path; help's own
// redirect_from pages (meta-refresh today) do the second hop. Follow both kinds, then judge
// where a browser actually ends up — not the first Location.
async function follow(url, hops = 6) {
  const trail = [url];
  for (let i = 0; i < hops; i++) {
    const res = await fetch(url, { redirect: 'manual' }).catch(() => null);
    if (!res) return { ok: false, trail };
    if ([301, 302, 307, 308].includes(res.status)) {
      url = new URL(res.headers.get('location') ?? '', url).href; trail.push(url); continue;
    }
    if (res.status === 200 && url.startsWith(HELP_HOST + '/')) {
      const m = (await res.text()).match(/http-equiv="refresh"\s+content="\d+;\s*url=([^"]+)"/i);
      if (m) { url = new URL(m[1], url).href; trail.push(url); continue; }
    }
    return { ok: res.status === 200, trail };
  }
  return { ok: false, trail };
}
const norm = (u) => u.replace(/^http:/, 'https:').replace(/\/$/, '');

async function live() {
  const rows = readTsv().filter((r) => r.status !== 'dies');
  let bad = 0;
  for (const r of rows) {
    const expected = r.status === 'external' ? r.tgt : HELP_HOST + (r.tgt || r.dev);
    const first = await fetch(DEV_HOST + r.dev, { redirect: 'manual' }).catch(() => null);
    const firstOk = !!first && [301, 308].includes(first.status);
    const end = await follow(DEV_HOST + r.dev);
    // off-site rows: judge at the first hop that leaves keboola.com — GitHub redirects on its own
    const landed = r.status === 'external'
      ? (end.trail.find((u) => !/\/\/[^/]*keboola\.com\//.test(u)) ?? end.trail.at(-1))
      : end.trail.at(-1);
    const ok = firstOk && norm(landed) === norm(expected) && (r.status === 'external' || end.ok);
    if (!ok) { bad++; console.error(`✗ ${r.dev}: ${first?.status ?? 'ERR'} → ${end.trail.slice(1).join(' → ') || '(no redirect)'} — want 301 … ${expected}`); }
  }
  console.log(bad ? `✗ ${bad}/${rows.length} mismatches` : `✓ all ${rows.length} URLs leave the dev domain with a 301 and land on their contract target`);
  if (bad) process.exit(1);
}

// vercel.json `redirects` for every row whose help URL differs from the dev path — makes the
// second hop a real 301 instead of a meta-refresh page. Printed, not written: wiring it into
// vercel.json is a production routing change and gets its own PR.
function vercel() {
  // external rows never reach help: the edge function answers /cli/* itself, and help's /cli/ is kbagent
  const rows = readTsv().filter((r) => r.status !== 'dies' && r.status !== 'external' && r.tgt && r.tgt !== r.dev);
  const redirects = rows.map((r) => ({ source: r.dev, destination: r.tgt, statusCode: 301 }));
  console.log(JSON.stringify({ redirects }, null, 2));
  console.error(`${redirects.length} rules — check Vercel's per-project redirect limit before wiring these in`);
}

function walk(dir, fn) { for (const e of fs.readdirSync(dir, { withFileTypes: true })) { const p = path.join(dir, e.name); e.isDirectory() ? walk(p, fn) : fn(p); } }
function count(a) { return a.reduce((m, x) => (m[x] = (m[x] ?? 0) + 1, m), {}); }
function fmt(o) { return Object.entries(o).map(([k, v]) => `${v} ${k}`).join(', '); }
function fail(msg) { console.error(`✗ ${msg}`); process.exit(1); }

if (mode === '--gen') gen();
else if (mode === '--build') checkBuild();
else if (mode === '--flippable') flippable();
else if (mode === '--live') await live();
else if (mode === '--vercel') vercel();
else fail('usage: check-redirects.mjs --gen | --build | --flippable | --live | --vercel');
